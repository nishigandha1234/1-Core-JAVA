import java.util.*;

public class CheckEqualityTwoInt
{
	public static void main(String x[])
	{
		Scanner sc = new Scanner(System.in);
		int num1 = sc.nextInt();
		int num2 = sc.nextInt();
		if(num1 == num2) System.out.println("Both the Integers are Equal");
		else System.out.println("Both the Integers are NOT Equal");
	}
}